/**
 * Three projects:
 * - `unit` runs anywhere, with no database or Docker secrets: `npm run test:unit`.
 * - `integration` needs PostgreSQL 18 with the schema loaded and migrated, as CI and
 *   CLAUDE.md ("DB-backed backend tests") set it up, and DATABASE_URL pointing at it.
 * - `migrations`: the tests that change the shared test database's schema in a
 *   transaction they roll back (a migration's UP or DOWN, other DDL, ACCESS EXCLUSIVE locks
 *   on the app's tables). They need the database too, and run one file at a time, after
 *   the other two have finished. Their DDL locks a table and then the tables it refers to;
 *   an app query in another file (SELECT app_timezone() reading tenant_settings, a test
 *   ledger's setup or cleanup) takes them the other way round, and running at once,
 *   Postgres failed one of the two with a deadlock (40P01).
 * `npm run test:integration` runs the last two (`test:migrations` only the last);
 * `npm test` / `npm run test:run` / `test:coverage` run all three, or only `unit` when
 * DATABASE_URL isn't set.
 *
 * A test that needs the database is named `*.db.test.ts`, or lives in
 * src/routes/__tests__/; a migration's test is named `*Migration.test.ts` (or
 * `*Migrations.db.test.ts` for several migrations'). CI runs the unit project without a
 * database too, so a database test with another name fails there.
 */
const SCHEMA_CHANGES = [
  'src/**/*Migration.test.ts',
  'src/**/*Migrations.db.test.ts',
  // Not a migration's, but schema changes all the same: roles and a table in a
  // transaction held for the whole file, and the schema-change lock's own tests
  // (test/schemaLock.ts), which hold ACCESS EXCLUSIVE locks on users and tenants.
  'src/__tests__/servingRole.test.ts',
  'src/test/__tests__/schemaLock.db.test.ts',
];
const INTEGRATION = [
  'src/**/*.db.test.ts',
  'src/routes/__tests__/**/*.test.ts',
  // Database tests named before that convention, kept as they are because CLAUDE.md and
  // other files name them. They skip themselves without a database.
  'src/__tests__/credential-revocation.test.ts',
  'src/__tests__/organization-membership.test.ts',
  'src/__tests__/personal-access-tokens.test.ts',
  'src/__tests__/rls-catalog.test.ts',
  'src/__tests__/rls-isolation.test.ts',
  'src/__tests__/route-authorization.test.ts',
  'src/__tests__/services/BackupService.advisoryLock.test.ts',
  'src/__tests__/tenant-isolation-api.test.ts',
];
const ALL_TESTS = ['src/**/*.{test,spec}.{ts,tsx}'];
// Only tests from source: dist is built for the migrations in CI.
const EXCLUDE = ['**/node_modules/**', '**/dist/**'];

const hasDatabase = Boolean(process.env.TEST_DATABASE_URL || process.env.DATABASE_URL);
const argv = process.argv.slice(2);
const DATABASE_PROJECTS = ['integration', 'migrations'];
const integrationRequested = argv.some(
  (arg, i) =>
    DATABASE_PROJECTS.some((name) => arg === `--project=${name}`) ||
    (arg === '--project' && DATABASE_PROJECTS.includes(argv[i + 1]))
);
if (integrationRequested && !hasDatabase) {
  throw new Error(
    'The integration tests need PostgreSQL: set DATABASE_URL (and the DB_* settings) as CONTRIBUTING.md ' +
    'describes, or run `npm run test:unit`.'
  );
}
if (!hasDatabase) {
  process.stderr.write(
    'DATABASE_URL is not set: running the unit tests only. The integration tests need PostgreSQL (see CONTRIBUTING.md).\n'
  );
}

// Modules that load the Docker secrets at import (db.ts) refuse to load without them; the
// unit tests never connect, so placeholders do.
const UNIT_SECRETS = {
  DB_PASSWORD: process.env.DB_PASSWORD ?? 'unit-test-db-password',
  JWT_SECRET: process.env.JWT_SECRET ?? 'unit-test-jwt-secret',
  SESSION_SECRET: process.env.SESSION_SECRET ?? 'unit-test-session-secret',
  CSRF_SECRET: process.env.CSRF_SECRET ?? 'unit-test-csrf-secret',
};

// Every source file counts, imported by a test or not: without `include`, Vitest
// measures only the files the tests load, and an untested file raises nothing.
const COVERAGE_INCLUDE = ['src/**/*.ts'];
const COVERAGE_EXCLUDE = [
  '**/*.d.ts',
  '**/*.{test,spec}.ts',
  '**/__tests__/**',
  '**/__mocks__/**',
  // Test helpers (fixtures, the per-file ledger), not the app.
  'src/test/**',
  // Generated by kysely-codegen: types only.
  'src/db/schema.generated.ts',
];
// Floors, so coverage can't drop unnoticed: about a point under what the
// suite measured over every source file, and at least one function, branch or line under.
// `npm run test:coverage` (CI) fails below them. Re-measured on 2026-11-08 over the
// whole suite twice, as statements/branches/functions/lines: with PG_BIN_DIR set, as CI has
// it (the backup round trip and the restore tests run), and without, as on a contributor's
// machine whose pg_dump isn't the server's (they skip). Each floor is under both, but one:
//   - global: 89.08/83.83/93.73/90.34 with, 87.02/82.89/91.92/88.17 without;
//   - db: 87.40/93.58/92.19/87.04 with, 84.96/92.66/85.94/85.19 without. The restore tests
//     reach db/ functions nothing else does, so its functions floor stays 88 (a floor isn't
//     lowered): a run without PG_BIN_DIR falls under it, as it did on main, so set PG_BIN_DIR
//     to run test:coverage locally. Its branches and lines floors rose (to 91 and 84); its
//     statements floor stayed 83;
//   - the others the same either way: middleware 98.21/92.79/98.06/98.66, the budget
//     services 93.33/83.71/100/93.66, the import pipeline 89.56/81.31/98.04/89.55,
//     transactions 97.91/93.97/100/99.61.
// The globs give the code a regression costs most in its own, higher floors; the global
// floors count those files too. The budget glob was 'src/services/Budget*', which matched
// BudgetService.ts and BudgetItemMatcher.ts only, not services/budgetItems/ and
// services/budgetPeriods/. Vitest lets a glob that matches no file pass, checking
// nothing, so moving one of these files means moving its glob; assertThresholdGlobsMatch
// refuses one that matches nothing. Raise floors as coverage grows; lowering
// one is a decision to make in review, not a way to get a change through.
const COVERAGE_THRESHOLDS = {
  statements: 86,
  branches: 81,
  functions: 90,
  lines: 87,
  'src/middleware/**': { statements: 97, branches: 91, functions: 97, lines: 97 },
  'src/db/**': { statements: 83, branches: 91, functions: 88, lines: 84 },
  'src/services/{Budget*,budgetItems/**,budgetPeriods/**}': { statements: 92, branches: 82, functions: 99, lines: 92 },
  'src/services/{ImportService.ts,import/**}': { statements: 88, branches: 80, functions: 97, lines: 88 },
  'src/services/transactions/**': { statements: 97, branches: 93, functions: 98, lines: 98 },
};

/**
 * Refuse a coverage.thresholds glob that matches none of the files coverage counts: Vitest
 * would apply its floors to nothing and pass. Matched as Vitest matches them (picomatch,
 * Vitest's own copy, on paths relative to this directory).
 */
function assertThresholdGlobsMatch(thresholds: Record<string, unknown>, include: string[], exclude: string[]): void {
  type Matcher = (glob: string | string[]) => (file: string) => boolean;
  const picomatch = createRequire(import.meta.resolve('vitest'))('picomatch') as Matcher;
  const [included, excluded] = [picomatch(include), picomatch(exclude)];
  const files = readdirSync(path.join(import.meta.dirname, 'src'), { recursive: true })
    .map((file) => path.posix.join('src', String(file).split(path.sep).join('/')))
    .filter((file) => included(file) && !excluded(file));
  const notGlobs = new Set(['statements', 'branches', 'functions', 'lines', 'perFile', 'autoUpdate', '100']);
  // A matcher called with a second argument returns an object, always truthy: call it with one.
  const matchesAny = (glob: string) => {
    const matches = picomatch(glob);
    return files.some((file) => matches(file));
  };
  const empty = Object.keys(thresholds).filter((key) => !notGlobs.has(key) && !matchesAny(key));
  if (empty.length > 0) {
    throw new Error(
      `No file coverage counts matches the coverage.thresholds glob ${empty.map((g) => `'${g}'`).join(', ')}, ` +
        'so its floors would check nothing: point it at where the code is now (vitest.config.ts).'
    );
  }
}
assertThresholdGlobsMatch(COVERAGE_THRESHOLDS, COVERAGE_INCLUDE, COVERAGE_EXCLUDE);

